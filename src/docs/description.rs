//! Render the Steam Workshop description from the HEMTT project name, the
//! version, and `mods.lock`. HEMTT converts Markdown to Steam Workshop
//! format at publish time, so the file stays readable in the repository.

use std::collections::HashSet;

use crate::lock::{Dependency, LockFile};

/// One Workshop item shown in the description.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Item {
    pub id: String,
    pub name: String,
}

/// Render Markdown. Sections with no entries are omitted.
pub fn render_description(name: &str, version: &str, lock: &LockFile) -> String {
    let included = included_items(lock);
    let included_ids: HashSet<&str> = included.iter().map(|item| item.id.as_str()).collect();
    let requirements = requirement_items(lock, &included_ids);

    let mut out = format!("# {name}\n\nVersion {version}\n");
    if !included.is_empty() {
        out.push_str("\n## Included Content\n\n");
        write_items(&mut out, &included);
    }
    if !requirements.is_empty() {
        out.push_str("\n## Requirements\n\n");
        write_items(&mut out, &requirements);
    }
    out.push_str(&format!("\n{}\n", super::MARKER));
    out
}

fn write_items(out: &mut String, items: &[Item]) {
    for item in items {
        out.push_str(&format!("- {} (Workshop ID: {})\n", item.name, item.id));
    }
}

/// Locked mods that contributed at least one file, sorted by name.
pub fn included_items(lock: &LockFile) -> Vec<Item> {
    let mut items: Vec<Item> = lock
        .mods
        .iter()
        .filter(|(_, entry)| !entry.files.is_empty())
        .map(|(id, entry)| Item {
            id: id.clone(),
            name: label(&entry.name, id),
        })
        .collect();
    sort_items(&mut items);
    items
}

/// The union of every dependency, minus the ids already included, sorted
/// by name. One entry per dependency id.
pub fn requirement_items(lock: &LockFile, included_ids: &HashSet<&str>) -> Vec<Item> {
    let mut seen: HashSet<&str> = HashSet::new();
    let mut items: Vec<Item> = Vec::new();
    for entry in lock.mods.values() {
        for dependency in &entry.dependencies {
            let Dependency { id, name } = dependency;
            if included_ids.contains(id.as_str()) || !seen.insert(id.as_str()) {
                continue;
            }
            items.push(Item {
                id: id.clone(),
                name: label(name, id),
            });
        }
    }
    sort_items(&mut items);
    items
}

fn sort_items(items: &mut [Item]) {
    items.sort_by(|a, b| {
        super::text::sort_key(&a.name)
            .cmp(&super::text::sort_key(&b.name))
            .then_with(|| a.name.cmp(&b.name))
            .then_with(|| a.id.cmp(&b.id))
    });
}

/// Use the id as the label when the lock file has no name.
fn label(name: &str, id: &str) -> String {
    if name.trim().is_empty() {
        id.to_string()
    } else {
        name.to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lock::ModLockEntry;
    use std::collections::HashMap;

    fn entry(name: &str, files: &[&str]) -> ModLockEntry {
        ModLockEntry {
            files: files.iter().map(|f| f.to_string()).collect(),
            name: name.to_string(),
            tags: Vec::new(),
            dependencies: Vec::new(),
            updated: String::new(),
        }
    }

    fn lock_with(entries: &[(&str, ModLockEntry)]) -> LockFile {
        LockFile {
            version: 1,
            mods: entries
                .iter()
                .map(|(id, entry)| (id.to_string(), entry.clone()))
                .collect::<HashMap<_, _>>(),
        }
    }

    fn dep(id: &str, name: &str) -> Dependency {
        Dependency {
            id: id.to_string(),
            name: name.to_string(),
        }
    }

    #[test]
    fn renders_title_and_version_without_lock_entries() {
        let text = render_description("Pack", "1.0.0.0", &lock_with(&[]));
        assert_eq!(
            text,
            "# Pack\n\nVersion 1.0.0.0\n\n[//]: # (generated by UKSFTA-Tools)\n"
        );
    }

    #[test]
    fn renders_included_content_sorted_by_name() {
        let lock = lock_with(&[
            ("2", entry("Zulu", &["addons/z.pbo"])),
            ("1", entry("Alpha", &["addons/a.pbo"])),
        ]);
        let text = render_description("Pack", "1.0.0.0", &lock);
        assert!(text.starts_with("# Pack\n\nVersion 1.0.0.0\n"));
        let alpha = text.find("- Alpha (Workshop ID: 1)").unwrap();
        let zulu = text.find("- Zulu (Workshop ID: 2)").unwrap();
        assert!(alpha < zulu);
        assert!(text.contains("## Included Content"));
    }

    #[test]
    fn sorting_ignores_case() {
        let lock = lock_with(&[
            ("1", entry("Zulu", &["addons/z.pbo"])),
            ("2", entry("kerama", &["addons/k.pbo"])),
        ]);
        let text = render_description("Pack", "1.0.0.0", &lock);
        let kerama = text.find("- kerama").unwrap();
        let zulu = text.find("- Zulu").unwrap();
        assert!(kerama < zulu);
    }

    #[test]
    fn omits_entries_without_files() {
        let lock = lock_with(&[("1", entry("Empty", &[]))]);
        let text = render_description("Pack", "1.0.0.0", &lock);
        assert!(!text.contains("Included Content"));
        assert!(!text.contains("Requirements"));
    }

    #[test]
    fn requirements_exclude_included_ids_and_dedupe() {
        let mut first = entry("First", &["addons/f.pbo"]);
        first.dependencies = vec![dep("9", "Shared"), dep("1", "Included Dep")];
        let mut second = entry("Second", &["addons/s.pbo"]);
        second.dependencies = vec![dep("9", "Shared"), dep("3", "Third")];
        let lock = lock_with(&[("1", first), ("2", second)]);

        let text = render_description("Pack", "1.0.0.0", &lock);
        assert_eq!(text.matches("Shared").count(), 1);
        assert!(!text.contains("Included Dep"));
        let shared = text.find("- Shared (Workshop ID: 9)").unwrap();
        let third = text.find("- Third (Workshop ID: 3)").unwrap();
        assert!(shared < third);
    }

    #[test]
    fn requirements_render_only_the_requirements_section() {
        let mut entry = entry("First", &["addons/f.pbo"]);
        entry.dependencies = vec![dep("9", "Shared")];
        let text = render_description("Pack", "1.0.0.0", &lock_with(&[("1", entry)]));
        assert!(text.contains("## Included Content\n\n- First (Workshop ID: 1)\n"));
        assert!(text.contains("## Requirements\n\n- Shared (Workshop ID: 9)\n"));
    }

    #[test]
    fn missing_dependency_name_uses_the_id() {
        let mut entry = entry("Included", &["addons/i.pbo"]);
        entry.dependencies = vec![dep("7", "")];
        let text = render_description("Pack", "1.0.0.0", &lock_with(&[("1", entry)]));
        assert!(text.contains("- 7 (Workshop ID: 7)"));
    }

    #[test]
    fn ends_with_the_generated_marker() {
        let text = render_description("Pack", "1.0.0.0", &lock_with(&[]));
        assert!(text.ends_with("\n[//]: # (generated by UKSFTA-Tools)\n"));
    }
}
