//! Regenerate the HEMTT publish description and changelog files.
//!
//! Only projects that declare `[hemtt.publish]` are touched. The generated
//! files stay in the repository, so `hemtt publish` uploads current text
//! instead of a stale copy.

mod changelog;
mod config;
mod date;
mod description;
mod discover;
mod names;
mod output;
mod state;
mod text;
mod version;

#[cfg(test)]
mod tests;

/// A Markdown link-reference definition. HEMTT's markdown-bbcode drops
/// definitions, so the marker never reaches Steam. A file or section
/// without it is treated as hand-written and is never replaced without
/// `--force`.
pub(crate) const MARKER: &str = "[//]: # (generated by UKSFTA-Tools)";

use std::path::Path;

use crate::error::UksftaError;
use crate::lock::load_lock;

use self::changelog::{changes_for, next_state, render_changelog, snapshot};
use self::config::{load_project, resolve_path};
use self::output::{project_name, read_existing, report_blocked, summarize, write_target};
use self::version::resolve_version;

/// Options for one `uksfta docs` run.
pub struct DocsOptions<'a> {
    pub root: Option<&'a Path>,
    pub dry_run: bool,
    pub check: bool,
    pub online: bool,
    pub refresh_names: bool,
    pub force: bool,
}

/// What one project did.
enum Outcome {
    Updated(Option<String>),
    Unchanged,
    Skipped(String),
}

/// Update every configured publish file. `--check` reports stale targets
/// and fails with [`UksftaError::Check`]; otherwise the files are rewritten.
pub fn docs(options: &DocsOptions<'_>) -> Result<(), UksftaError> {
    let projects = discover::find_projects(options.root)?;
    if projects.is_empty() {
        return Err(UksftaError::Input(
            "no .hemtt/project.toml found. Use --root <PATH> to search a directory.".to_string(),
        ));
    }

    let mut stale = Vec::new();
    for root in &projects {
        match run_project(root, options, &mut stale)? {
            Outcome::Skipped(reason) => println!("{}: skipped ({reason})", root.display()),
            Outcome::Updated(_) | Outcome::Unchanged if options.check => {}
            Outcome::Updated(Some(detail)) => {
                println!("{}: updated ({detail})", root.display())
            }
            Outcome::Updated(None) => println!("{}: updated", root.display()),
            Outcome::Unchanged => println!("{}: unchanged", root.display()),
        }
    }

    if options.check {
        if stale.is_empty() {
            println!("All publish files are up to date.");
            return Ok(());
        }
        return Err(UksftaError::Check(format!(
            "{} publish file(s) are missing or stale: {}",
            stale.len(),
            stale.join(", ")
        )));
    }
    Ok(())
}

fn run_project(
    root: &Path,
    options: &DocsOptions<'_>,
    stale: &mut Vec<String>,
) -> Result<Outcome, UksftaError> {
    let project = load_project(root)?;
    let publish = match project.publish {
        Some(publish) if !publish.is_empty() => publish,
        _ => return Ok(Outcome::Skipped("no [hemtt.publish]".to_string())),
    };

    let Some(project_version) = resolve_version(root, project.version_path.as_deref()) else {
        eprintln!(
            "Warning: {} has no readable version. Project skipped.",
            root.display()
        );
        return Ok(Outcome::Skipped("no version".to_string()));
    };
    let version = project_version.to_string();
    let changelog_version = project_version.short();
    if publish.changelog.is_some()
        && (project_version.build.is_some() || project.git_hash.unwrap_or(8) != 0)
    {
        eprintln!(
            "Warning: {}: HEMTT publish uses changelog key {version:?}, but its parser accepts only {changelog_version:?}. Set [version] git_hash = 0 and omit BUILD to use the changelog.",
            root.display()
        );
    }

    let lock_path = root.join("mods.lock");
    if !lock_path.is_file() {
        let targets: Vec<&str> = [publish.description.as_deref(), publish.changelog.as_deref()]
            .into_iter()
            .flatten()
            .collect();
        eprintln!(
            "Warning: {}: mods.lock is missing. Not updated: {}",
            root.display(),
            targets.join(", ")
        );
        return Ok(Outcome::Skipped("no mods.lock".to_string()));
    }
    let lock = load_lock(&lock_path)?;

    let mut changed = false;
    let mut detail = None;
    let mut blocked: Option<String> = None;

    if let Some(relative) = &publish.description {
        let path = resolve_path(root, relative)?;
        let existing = read_existing(&path)?;
        if !options.force
            && existing
                .as_deref()
                .is_some_and(|text| !text.contains(MARKER))
        {
            report_blocked(
                &path,
                options,
                stale,
                "description was not generated by uksfta",
            );
            blocked.get_or_insert_with(|| "unmarked file; use --force".to_string());
        } else {
            let name = project_name(&project.name, root);
            let mut display_lock = lock.clone();
            let cache_path = root.join(".uksfta").join("workshop-names.json");
            let mut cache = names::load_cache(&cache_path).unwrap_or_else(|e| {
                eprintln!("Warning: {}: {e}", root.display());
                Default::default()
            });
            let mut lookup_failed = false;
            if options.online {
                let before = cache.clone();
                match names::resolve_missing(&display_lock, &mut cache, options.refresh_names) {
                    Ok(0) => {}
                    Ok(count) => {
                        println!("{}: resolved {count} Workshop name(s)", root.display())
                    }
                    Err(e) => {
                        eprintln!(
                            "Warning: {}: Workshop name lookup failed: {e}",
                            root.display()
                        );
                        lookup_failed = true;
                    }
                }
                names::prune_cache(&mut cache, &lock);
                if cache != before && !options.check && !options.dry_run {
                    if let Err(e) = names::save_cache(&cache_path, &cache) {
                        eprintln!("Warning: {}: {e}", root.display());
                    }
                }
            }
            if lookup_failed && !names::ids_to_fetch(&lock, &cache, false).is_empty() {
                report_blocked(
                    &path,
                    options,
                    stale,
                    "Workshop name lookup failed; description not updated",
                );
                blocked.get_or_insert_with(|| "Workshop name lookup failed".to_string());
            } else {
                names::apply_names(&mut display_lock, &cache);
                let content = description::render_description(&name, &version, &display_lock);
                changed |= write_target(&path, &content, options, stale)?;
            }
        }
    }

    if let Some(relative) = &publish.changelog {
        let path = resolve_path(root, relative)?;
        let existing = read_existing(&path)?;
        if !options.force && !changelog::can_replace(existing.as_deref(), &changelog_version) {
            report_blocked(
                &path,
                options,
                stale,
                "changelog section was not generated by uksfta",
            );
            blocked.get_or_insert_with(|| "unmarked file; use --force".to_string());
        } else {
            let current = snapshot(&lock);
            let state_path = root.join(".uksfta").join("publish-state.json");
            let previous = state::load(&state_path)?;
            let changes = changes_for(previous.as_ref(), &changelog_version, &current);
            let content = render_changelog(
                existing.as_deref(),
                &changelog_version,
                &date::today_utc(),
                &changes,
            );
            changed |= write_target(&path, &content, options, stale)?;
            detail = summarize(&changes);

            if !options.check && !options.dry_run {
                let next = next_state(previous.as_ref(), &changelog_version, &current);
                if previous.as_ref() != Some(&next) {
                    state::save(&state_path, &next)?;
                }
            }
        }
    }

    Ok(if changed {
        Outcome::Updated(detail)
    } else if let Some(reason) = blocked {
        Outcome::Skipped(reason)
    } else {
        Outcome::Unchanged
    })
}
